export const LOCALES = ["en", "zh-CN"] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "en";
export const resources: Record<Locale, Resource> = { en, "zh-CN": zhCN };

/** `zh`, `zh-Hans`, `zh-CN`, `zh_CN` all use the Simplified Chinese resource; everything else is English. */
export function normalizeLocale(value: string | undefined): Locale {
  const lower = (value ?? "").trim().toLowerCase();
  return lower === "zh" || lower.startsWith("zh-") || lower.startsWith("zh_") ? "zh-CN" : "en";
}

type Vars = Record<string, string | number>;

/** Resolve a dotted key from the same resources the client uses. Missing keys return the key. */
export function translate(locale: Locale, key: string, vars?: Vars): string {
  const value = key.split(".").reduce<unknown>((node, part) => {
    if (node && typeof node === "object") return (node as Record<string, unknown>)[part];
    return undefined;
  }, resources[locale]);

  if (typeof value !== "string") return key;
  return value.replace(/\{\{\s*([^},\s]+)[^}]*\}\}/g, (_, name: string) => {
    const replacement = vars?.[name];
    return replacement === undefined ? "" : String(replacement);
  });
}
